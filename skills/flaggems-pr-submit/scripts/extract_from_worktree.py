def find_test_function(op, worktree):
    """Find and extract test function(s) for the operator from worktree.

    Search priority:
    1. test_accuracy_<op_id> — most common pattern
    2. test_accuracy_<op_name> — underscore-prefixed variant
    3. test_<op_id> — no accuracy prefix (reflection_pad3d, embedding etc.)
    4. Any function decorated with @pytest.mark.<op_id>
    """
    tests_dir = os.path.join(worktree, "tests")
    op_id = get_op_id(op)

    # Worktree generators sometimes keep the leading underscore on both the test
    # function name and the pytest mark (e.g. ``test__cslt_compress`` /
    # ``@pytest.mark._cslt_compress``) even when the skill's canonical id strips
    # it. Search both the stripped ``op_id`` and the raw ``op`` (underscore form)
    # so the lookup is robust to that generator convention.
    name_variants = [op_id]
    if op.startswith("_") and op not in name_variants:
        name_variants.append(op)

    candidates = []
    for v in name_variants:
        candidates.append(f"test_accuracy_{v}")
        candidates.append(f"test_{v}")
    candidates = [c for c in candidates if c]

    # When the worktree keeps the leading underscore on the test file name
    # (e.g. ``test__conj_physical.py`` for op ``_conj_physical``), prefer that
    # file over a same-named synthetic ``test_conj_physical.py`` that some
    # generators leave behind. Build a preferred-filename map keyed by the
    # raw op so the double-underscore file wins ties.
    raw_pref_file = f"test_{op}.py" if op.startswith("_") else None

    def _scan_for(target_func, prefer_file=None):
        hits = []
        for fname in os.listdir(tests_dir):
            if not fname.endswith(".py"):
                continue
            if prefer_file and fname == prefer_file:
                continue  # handle preferred file separately below
            fpath = os.path.join(tests_dir, fname)
            with open(fpath) as f:
                content = f.read()
            if f"def {target_func}" in content:
                hits.append((fpath, content))
        return hits

    # First, try the preferred raw-op file (exact name) if it exists.
    if raw_pref_file:
        pref_path = os.path.join(tests_dir, raw_pref_file)
        if os.path.isfile(pref_path):
            with open(pref_path) as f:
                pref_content = f.read()
            for target_func in candidates:
                if f"def {target_func}" in pref_content:
                    return pref_path, pref_content, target_func

    for target_func in candidates:
        hits = _scan_for(target_func)
        if hits:
            fpath, content = hits[0]
            return fpath, content, target_func

    # Fallback: find by @pytest.mark.<variant> (stripped id first, then raw op)
    for v in name_variants:
        mark_pattern = f"@pytest.mark.{v}"
        # Prefer the raw-op file when scanning marks too.
        scan_files = []
        if raw_pref_file and os.path.isfile(os.path.join(tests_dir, raw_pref_file)):
            scan_files.append(raw_pref_file)
        for fname in os.listdir(tests_dir):
            if not fname.endswith(".py"):
                continue
            if fname in scan_files:
                continue
            scan_files.append(fname)
        for fname in scan_files:
            fpath = os.path.join(tests_dir, fname)
            with open(fpath) as f:
                content = f.read()
            if mark_pattern in content:
                # Find the first test function after the mark
                match = re.search(rf"{re.escape(mark_pattern)}.*?def\s+(test_\w+)", content, re.DOTALL)
                if match:
                    return fpath, content, match.group(1)

    return None, None, None


def find_all_related_test_functions(content, op_id, primary_func_name, op=None):
    """Find all test functions related to the operator in the same file.

    Looks for functions decorated with @pytest.mark.<op_id> (or the raw
    underscore-prefixed mark when the worktree kept the leading underscore).
    """
    func_names = []
    marks = [f"@pytest.mark.{op_id}"]
    if op and op.startswith("_") and op != op_id:
        marks.append(f"@pytest.mark.{op}")

    for mark in marks:
        # Use regex to find all def lines preceded (somewhere above) by the mark
        # Pattern: @pytest.mark.<variant> followed eventually by def test_xxx
        for m in re.finditer(
            rf"^{re.escape(mark)}\s*\n(?:.*\n)*?^\s*def\s+(test_\w+)",
            content, re.MULTILINE
        ):
            fn = m.group(1)
            if fn not in func_names:
                func_names.append(fn)

    if not func_names and primary_func_name:
        func_names = [primary_func_name]

    return func_names



def extract_assignment_block(content, name):
    """Extract a NAME = ... assignment, including preceding comments.

    Handles both top-level (``NAME = ...``) and conditionally-defined constants
    that generators place inside a top-level ``if cfg.QUICK_MODE:`` / ``else:``
    block (e.g. ``CONJ_PHYSICAL_SHAPES``). For the conditional form, the
    non-quick (``else``) branch value is extracted and dedented so the test
    module can use it without the ``cfg`` import.
    """
    lines = content.split("\n")
    # Collect all candidate assignments (there may be two: one under
    # ``if cfg.QUICK_MODE:`` and one under ``else:``). Prefer the non-quick
    # (else) branch — it carries the full shape set used in CI.
    candidates = []
    for i, line in enumerate(lines):
        m = re.match(rf"^(\s*){re.escape(name)}\s*=", line)
        if m:
            candidates.append((i, m.group(1)))
    if not candidates:
        return None
    # Heuristic: if more than one candidate, prefer the one under the non-quick
    # ``else:`` branch. Generators place a constant in both ``if cfg.QUICK_MODE:``
    # and ``else:`` blocks; the else branch carries the full CI value. The else
    # keyword may be several lines above the assignment (separated by other
    # assignments in the same block), so use the AST to determine which top-level
    # ``if``/``else`` branch each candidate assignment lives in.
    import ast as _ast

    else_line = None
    try:
        tree = _ast.parse(content)
    except SyntaxError:
        tree = None
    if tree is not None:
        for node in tree.body:
            if isinstance(node, _ast.If):
                # The else branch (node.orelse) holds the full-mode constants.
                for sub in node.orelse:
                    if (
                        isinstance(sub, _ast.Assign)
                        and sub.targets
                        and isinstance(sub.targets[0], _ast.Name)
                        and sub.targets[0].id == name
                    ):
                        else_line = sub.lineno - 1  # 0-indexed

    start, indent = candidates[0]
    if else_line is not None:
        for ci, (i, ind) in enumerate(candidates):
            if i == else_line:
                start, indent = i, ind
                break
    elif len(candidates) > 1:
        # AST-free fallback: prefer the candidate whose enclosing branch (by
        # indentation walk) is ``else:``. Only used if parsing failed.
        def enclosing_branch(i, indent_str):
            depth = 0
            j = i - 1
            while j >= 0:
                s = lines[j].strip()
                if s == "":
                    j -= 1
                    continue
                depth += s.count(")") + s.count("]") + s.count("}")
                depth -= s.count("(") + s.count("[") + s.count("{")
                if lines[j].startswith(indent_str) and depth <= 0:
                    if s == "else:":
                        return "else"
                    if s.startswith("if ") and s.endswith(":"):
                        return "if"
                j -= 1
            return None

        for ci, (i, ind) in enumerate(candidates):
            if enclosing_branch(i, ind) == "else":
                start, indent = i, ind
                break

    # Walk back to capture preceding comments (at the same indent or deeper).
    comment_start = start
    j = start - 1
    while j >= 0 and lines[j].strip().startswith("#"):
        comment_start = j
        j -= 1

    # Walk forward to find where the assignment's value ends (balanced
    # brackets). The closing line is part of the block. Trailing comment/blank
    # lines after the close belong to the NEXT statement (e.g. a comment above
    # the following constant), so they must NOT be included.
    end = start + 1
    balance = 0
    closed_at = None
    for i in range(start, len(lines)):
        line = lines[i]
        balance += (
            line.count("(") + line.count("[") + line.count("{")
            - line.count(")") - line.count("]") - line.count("}")
        )
        if balance <= 0:
            # Brackets closed on this line (or single-line balanced assignment).
            # Record it as the tentative close. A pure comment/blank line that
            # happens to balance does not count as the close.
            if line.strip() != "" and not line.strip().startswith("#"):
                closed_at = i
                break
            elif i == start:
                # Single-line assignment that is itself balanced (no brackets
                # or balanced on one line) — the close is this line.
                closed_at = i
                break
    if closed_at is not None:
        end = closed_at + 1

    block_lines = lines[comment_start:end]
    # Dedent by the assignment's indent so the block is module-level.
    if indent:
        dedented = []
        for ln in block_lines:
            if ln.startswith(indent):
                dedented.append(ln[len(indent):])
            else:
                dedented.append(ln)
        block_lines = dedented
    return "\n".join(block_lines).rstrip()


def extract_referenced_constants(content, block_text):
    names = sorted(set(re.findall(r"\b[A-Z][A-Z0-9_]{2,}\b", block_text)))
    blocks = []
    for name in names:
        block = extract_assignment_block(content, name)
        if block:
            # Rule 22: hardcoded shape lists (e.g. ``CONJ_PHYSICAL_SHAPES``) need
            # an explanatory comment. The worktree's value came from the
            # generator's non-quick CI branch; document that origin so the
            # check_operator hardcode-size check is satisfied.
            if name.endswith("SHAPES") and not block.lstrip().startswith("#"):
                block = f"# Core shapes exercised by {name} (mirrors worktree CI branch).\n{block}"
            # Rule 2: a local dtype restriction (e.g. ``FLOAT_DTYPES = [float16,
            # float32]`` excluding bfloat16) needs an immediate-preceding comment
            # so the dtype-hardcoding check treats it as intentional. The
            # generator restricts dtype lists for numerical-stability reasons;
            # document that so the literal list is allowed.
            if (
                name in ("FLOAT_DTYPES", "ALL_FLOAT_DTYPES", "PRIMARY_FLOAT_DTYPES")
                and not block.lstrip().startswith("#")
                and re.search(r"\[torch\.(float16|float32|bfloat16|float64)", block)
            ):
                block = (
                    "# Restricted dtype list: the generator limits the tested "
                    "precisions for numerical-stability reasons (see worktree).\n"
                    + block
                )
            blocks.append(block)
    return blocks

def extract_function_block(content, func_name):
    """Extract a function and its decorators from source code."""
    lines = content.split("\n")
    func_start = None
    decorator_start = None
    func_end = None

    for i, line in enumerate(lines):
        if f"def {func_name}" in line or f"class {func_name}" in line:
            func_start = i
            # Walk backwards to find decorators, including multi-line parametrize blocks.
            decorator_start = i
            j = i - 1
            balance = 0
            while j >= 0:
                stripped = lines[j].strip()
                if stripped == "" and balance == 0:
                    break
                if balance > 0 or stripped.startswith("@") or stripped.startswith((")", "]", "}")):
                    decorator_start = j
                    balance += (
                        stripped.count(")") + stripped.count("]") + stripped.count("}")
                        - stripped.count("(") - stripped.count("[") - stripped.count("{")
                    )
                    if stripped.startswith("@") and balance <= 0:
                        balance = 0
                    j -= 1
                    continue
                break
            break

    if func_start is None:
        return None

    # Find function end (next def/class at same or lower indent, or EOF)
    indent = len(lines[func_start]) - len(lines[func_start].lstrip())
    for i in range(func_start + 1, len(lines)):
        line = lines[i]
        if line.strip() == "":
            continue
        line_indent = len(line) - len(line.lstrip())
        if line_indent <= indent and (line.strip().startswith("def ") or
                                       line.strip().startswith("class ") or
                                       line.strip().startswith("@")):
            # Check if decorator belongs to this function
            if i > func_start + 1:
                func_end = i
                break
    if func_end is None:
        func_end = len(lines)

    # Trim trailing blank lines
    while func_end > decorator_start and lines[func_end - 1].strip() == "":
        func_end -= 1

    return "\n".join(lines[decorator_start:func_end])


def convert_test_imports(func_block, op, resolved_id=None, local_names=None):
    """Convert direct accuracy_utils imports to `utils.` prefix style.

    ``resolved_id`` is the conflict-aware canonical id (from
    ``resolve_op_names``): it keeps the leading underscore for conflict ops
    (e.g. ``_conj_physical``) and strips it otherwise (e.g. ``cslt_compress``).
    Test function names are normalized to ``test_<resolved_id>`` so the
    per-function mark check (which derives the expected mark from the function
    name suffix) sees a consistent variant id.

    ``local_names`` is the set of module-level names the test module defines
    itself (e.g. a local ``FLOAT_DTYPES = [torch.float16, torch.float32]``
    used to restrict tested dtypes). Such names must NOT be rewritten to
    ``utils.<sym>`` — the local definition shadows the accuracy_utils symbol
    and rewriting would both orphan the local constant and broaden the
    tested dtype set beyond the generator's intent.
    """
    if resolved_id is None:
        resolved_id = get_op_id(op)
    op_id = get_op_id(op)
    result = func_block
    local_names = local_names or set()

    # Replace function name: test_accuracy_<op> → test_<resolved_id>
    result = re.sub(rf"def test_accuracy_{re.escape(op_id)}\b",
                    f"def test_{resolved_id}", result)
    if op.startswith("_"):
        result = re.sub(rf"def test_accuracy_{re.escape(op)}\b",
                        f"def test_{resolved_id}", result)
        # Worktree generators that keep the leading underscore use double-underscore
        # test names (e.g. ``def test__cslt_compress``); normalize to the resolved id
        # (stripped for non-conflict, kept-underscore for conflict).
        result = re.sub(rf"def test_{re.escape(op)}\b",
                        f"def test_{resolved_id}", result)

    # Replace bare symbols with utils. prefix
    for sym in UTILS_SYMBOLS:
        # Skip symbols that the test module defines locally (a local
        # ``FLOAT_DTYPES = [...]`` restriction shadows the utils constant).
        if sym in local_names:
            continue
        # Only replace bare occurrences (not already prefixed)
        result = re.sub(rf"(?<!\.)(?<!\w){re.escape(sym)}\b", f"utils.{sym}", result)

    # Note: do NOT rewrite ``device=device`` → ``device=flag_gems.device``.
    # Worktree tests often define a local ``device = flag_gems.device`` and
    # pass ``device=device``; rewriting the call site makes the local binding
    # unused (flake8 F841) while leaving the dead assignment behind.

    # Remove vendor-specific branches
    result = re.sub(
        r"\s*if flag_gems\.vendor_name\s*==\s*[\"']kunlunxin[\"'].*?(?=\n\S|\n@|\Z)",
        "", result, flags=re.DOTALL
    )

    return result


def extract_test(op, worktree, repo, dry_run):
    section("Step 2: Test 文件")
    op_id = get_op_id(op)  # 读取 worktree 用（生成名，无冲突）
    # 最终文件名用 resolve_op_names：冲突场景保留前导下划线。
    file_op_id = resolve_op_names(repo, op)[0]
    dst = os.path.join(repo, f"tests/test_{file_op_id}.py")

    fpath, content, func_name = find_test_function(op, worktree)
    if not fpath:
        fatal(f"worktree 中未找到 test_accuracy_{op_id} 或 test_{op_id} 函数")

    ok(f"找到测试: {os.path.basename(fpath)}:{func_name}")

    # Find all related test functions (including variants like _list_padding, _empty_padding)
    all_funcs = find_all_related_test_functions(content, op_id, func_name, op=op)
    ok(f"找到 {len(all_funcs)} 个相关测试函数: {', '.join(all_funcs)}")

    # Module-level names the test defines itself (e.g. a local
    # ``FLOAT_DTYPES = [...]`` restriction). Such names must NOT be rewritten to
    # ``utils.<sym>`` — they shadow the accuracy_utils symbol and rewriting would
    # orphan the local constant and broaden the tested dtype set. Generators
    # place these constants inside a top-level ``if QUICK_MODE: / else:`` block,
    # so walk into ``If`` bodies too.
    local_names = set()
    try:
        import ast as _ast

        def _collect_assign_names(nodes):
            for node in nodes:
                if isinstance(node, _ast.Assign):
                    for tgt in node.targets:
                        if isinstance(tgt, _ast.Name):
                            local_names.add(tgt.id)
                elif isinstance(node, _ast.If):
                    _collect_assign_names(node.body)
                    _collect_assign_names(node.orelse)
        _collect_assign_names(_ast.parse(content).body)
    except SyntaxError:
        pass

    blocks = []
    for fn in all_funcs:
        block = extract_function_block(content, fn)
        if block:
            block = convert_test_imports(block, op, resolved_id=file_op_id, local_names=local_names)
            blocks.append(block)

    if not blocks:
        fatal(f"无法提取函数 {func_name}")

    # Capture module-level helper functions (e.g. ``_make_24_sparse``,
    # ``_prune_to_2x4``) referenced by the test functions. The worktree generators
    # define these at module scope and the extracted tests reference them, so we
    # must carry them over (plus the constants they use). Resolve the full
    # transitive closure: a helper may itself call other module-level helpers.
    block_text = "\n".join(blocks)
    helper_blocks = []
    discovered = set()
    # seed with names called from the test function blocks
    frontier = {h.rstrip("(").strip() for h in re.findall(r"\b_+\w+\s*\(", block_text)}
    frontier = {h for h in frontier if not h.startswith("test_")}
    while frontier:
        hname = frontier.pop()
        if hname in discovered:
            continue
        discovered.add(hname)
        m = re.search(rf"^def {re.escape(hname)}\b", content, re.MULTILINE)
        if not m:
            continue
        hblock = extract_function_block(content, hname)
        if not hblock or hblock in helper_blocks:
            continue
        helper_blocks.append(hblock)
        # names called from within this helper → expand the frontier
        for sub in re.findall(r"\b(_+\w+)\s*\(", hblock):
            sub = sub.rstrip("(").strip()
            if sub.startswith("test_") or sub in discovered:
                continue
            frontier.add(sub)
    if helper_blocks:
        helper_constants = extract_referenced_constants(content, "\n".join(helper_blocks))
        helper_blocks = helper_constants + helper_blocks
        ok(f"提取到 {len(helper_blocks)} 个测试辅助函数/常量")

    # Detect extra imports the test body needs beyond the fixed header, e.g.
    # ``from flag_gems.ops._cslt_compress import _cslt_compress_ref``. Only keep
    # flag_gems.ops.* imports (references into the op's own kernel module).
    extra_imports = re.findall(
        r"^from (flag_gems\.ops\.\w+) import (.+)$", content, re.MULTILINE
    )
    extra_import_lines = [f"from {mod} import {names}" for mod, names in extra_imports]

    # Detect stdlib module usage (e.g. ``math.prod``) in the extracted test body
    # and add the corresponding ``import <mod>``. The fixed header only includes
    # pytest/torch/flag_gems/utils, so a body that calls ``math.prod`` would
    # otherwise hit F821 undefined name 'math' under pre-commit.
    stdlib_used = set()
    for mod in ("math", "itertools", "functools", "operator", "collections", "copy"):
        if re.search(rf"\b{mod}\.\w", block_text):
            stdlib_used.add(mod)
    # Preserve the source's original stdlib import order where possible.
    src_import_order = []
    for line in content.split("\n"):
        m = re.match(r"^import (math|itertools|functools|operator|collections|copy)\b", line)
        if m and m.group(1) in stdlib_used and m.group(1) not in src_import_order:
            src_import_order.append(m.group(1))
    for mod in src_import_order:
        extra_import_lines.append(f"import {mod}")
    for mod in sorted(stdlib_used):
        if mod not in src_import_order:
            extra_import_lines.append(f"import {mod}")

    constants = extract_referenced_constants(content, block_text)
    combined_blocks = "\n\n\n".join(constants + helper_blocks + blocks)

    # Normalize the pytest marker to the canonical mark resolved for this repo.
    # Two cases need normalization:
    #   * conflict (bare op exists): mark becomes underscore_<bare>
    #   * non-conflict (default): leading underscore is stripped → <bare>,
    #     but the worktree generator may have kept ``_`` (e.g. ``@pytest.mark._cslt_compress``),
    #     which must be rewritten to the stripped canonical mark.
    resolved_id, resolved_mark = resolve_op_names(repo, op)
    if op.startswith("_"):
        # Rewrite the raw underscore mark → resolved mark (covers both cases).
        combined_blocks = re.sub(
            rf"@pytest\.mark\.{re.escape(op)}\b",
            f"@pytest.mark.{resolved_mark}", combined_blocks,
        )
    if resolved_mark != resolved_id:
        # worktree 生成的 mark 可能是 <bare> 或 _<bare>，统一改成 underscore_<bare>
        combined_blocks = re.sub(
            rf"@pytest\.mark\.{re.escape(op_id)}\b",
            f"@pytest.mark.{resolved_mark}", combined_blocks,
        )

    # Normalize variant test function names that kept a double-underscore prefix
    # (e.g. ``def test__cslt_compress_all_patterns`` → ``def test_cslt_compress_all_patterns``).
    if op.startswith("_"):
        combined_blocks = re.sub(
            rf"def test_{re.escape(op)}(?=\b|_)",
            f"def test_{resolved_id}", combined_blocks,
        )

    # Variant-specific marks: a function named ``test_<resolved_id>_out`` is a
    # real overload variant and must carry ``@pytest.mark.<resolved_mark>_out``
    # (not the base canonical mark). The worktree tags every function with the
    # base mark, so rewrite the mark on the decorator immediately preceding
    # each ``_out`` (and other real-variant suffix) test function. group(3) is
    # the bare suffix (e.g. ``out``) without the leading underscore.
    var_mark_suffixes = ["out"]
    cb_lines = combined_blocks.split("\n")
    for i, line in enumerate(cb_lines):
        m = re.match(rf"def (test_{re.escape(resolved_id)})(_(\w+))?\b", line)
        if not m:
            continue
        suffix = m.group(3)
        if suffix not in var_mark_suffixes:
            continue
        # find nearest preceding @pytest.mark.<resolved_mark> line
        for j in range(i - 1, max(i - 6, -1), -1):
            mk = re.match(rf"(\s*@pytest\.mark\.){re.escape(resolved_mark)}\b\s*$", cb_lines[j])
            if mk:
                cb_lines[j] = f"{mk.group(1)}{resolved_mark}_{suffix}"
                break
    combined_blocks = "\n".join(cb_lines)

    header_lines = [
        "import pytest",
        "import torch",
        "",
        "import flag_gems",
    ]
    for line in extra_import_lines:
        header_lines.append(line)
    header_lines += ["", "from . import accuracy_utils as utils", "", ""]
    test_content = "\n".join(header_lines) + f"{combined_blocks}\n"

    if dry_run:
        ok(f"[DRY] 将写入 {dst}")
        print(f"    预览:\n{test_content[:500]}")
    else:
        with open(dst, "w") as f:
            f.write(test_content)
        ok(f"已生成: {dst}")


