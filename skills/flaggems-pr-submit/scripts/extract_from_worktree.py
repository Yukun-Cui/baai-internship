def find_benchmark_code(op, worktree):
    """Find benchmark code for the operator in worktree."""
    op_id = get_op_id(op)
    bench_dir = os.path.join(worktree, "benchmark")

    # Search both the stripped id and the raw underscore-prefixed op, because the
    # worktree generator may keep the leading underscore in mark/op_name.
    search_variants = [op_id]
    if op.startswith("_") and op not in search_variants:
        search_variants.append(op)

    for fname in os.listdir(bench_dir):
        if not fname.endswith(".py"):
            continue
        fpath = os.path.join(bench_dir, fname)
        with open(fpath) as f:
            content = f.read()
        for v in search_variants:
            if (f"mark.{v}" in content or f'op_name="{v}"' in content
                    or f'"{v}"' in content):
                return fpath, content

    return None, None


def extract_benchmark_block(content, op, source_file):
    """Extract benchmark related code (class, input_fn, test function)."""
    op_id = get_op_id(op)
    lines = content.split("\n")
    blocks = []

    # Strategy 1: Find standalone class + test function (e.g., RandintBenchmark)
    op_key = re.sub(r"[^0-9A-Za-z]+", "", op_id).lower()
    for i, line in enumerate(lines):
        class_match = re.search(r"class\s+(\w*Benchmark)\b", line)
        if not class_match:
            continue
        cls_name = class_match.group(1)
        cls_key = re.sub(r"[^0-9A-Za-z]+", "", cls_name).lower()
        if op_key not in cls_key:
            continue
        block = extract_function_block(content, cls_name)
        if block:
            blocks.append(("class", block))

    # Strategy 1b: the benchmark class name may abbreviate the op (e.g.
    # ``ConvDoubleBackwardBenchmark`` for ``convolution_double_backward``), so
    # the substring match above misses it. Scan the test function body for a
    # ``XxxBenchmark(...)`` instantiation and extract that class directly.
    if not any(t == "class" for t, _ in blocks):
        instantiated = set()
        for pat in (
            rf"def test_(?:perf_)?{re.escape(op_id)}(?:_\w+)?\b",
            rf"def test_(?:perf_)?{re.escape(op)}(?:_\w+)?\b" if op != op_id else "",
        ):
            if not pat:
                continue
            for i, line in enumerate(lines):
                if re.search(pat, line):
                    tblock = extract_function_block(content, re.search(r"def (\w+)", line).group(1))
                    if tblock:
                        instantiated.update(re.findall(r"(\w*Benchmark)\s*\(", tblock))
        for cls_name in instantiated:
            if any(cls_name == b for _, b in blocks):
                continue
            block = extract_function_block(content, cls_name)
            if block:
                blocks.append(("class", block))

    # Strategy 2: Find input_fn for this op
    input_fn_names = [
        f"{op_id}_input_fn", f"_{op_id}_input_fn", f"_input_fn",
    ]
    for fn_name in input_fn_names:
        for i, line in enumerate(lines):
            if f"def {fn_name}" in line:
                block = extract_function_block(content, fn_name)
                if block:
                    blocks.append(("input_fn", block))
                break

    # Strategy 3: Find standalone test function (e.g. test_perf_randint).
    # Match both the stripped op_id and the raw underscore-prefixed op, because
    # the worktree generator may keep the leading underscore in the test name
    # (e.g. ``def test__cslt_compress``). Capture ALL variants sharing the
    # op prefix (e.g. ``test__conj_physical`` and ``test__conj_physical_out``)
    # so multi-overload benchmarks aren't dropped.
    search_names = [op_id]
    if op.startswith("_") and op != op_id:
        search_names.append(op)
    test_patterns = []
    for name in search_names:
        test_patterns.append(rf"def test_(?:perf_)?{re.escape(name)}(?:_\w+)?\b")

    captured_test_names = set()
    for pat in test_patterns:
        for i, line in enumerate(lines):
            m = re.search(pat, line)
            if m:
                fname = re.search(r"def (\w+)", line).group(1)
                if fname in captured_test_names:
                    continue
                captured_test_names.add(fname)
                block = extract_function_block(content, fname)
                if block:
                    blocks.append(("test", block))
        if any(t == "test" for t, _ in blocks):
            break

    # Strategy 4: op in a parametrized list → generate standalone benchmark
    if not any(t == "test" for t, _ in blocks):
        list_entry = _find_list_entry(lines, op_id, source_file)
        if list_entry:
            blocks.append(("list_entry", list_entry))

    if blocks:
        block_text = "\n".join(b for _, b in blocks if isinstance(b, str))
        constants = extract_referenced_constants(content, block_text)
        for const_block in reversed(constants):
            blocks.insert(0, ("constant", const_block))

    return blocks


def _find_list_entry(lines, op_id, source_file):
    """Find op in a parametrized operations list and return benchmark info dict."""
    basename = os.path.basename(source_file) if source_file else ""

    for i, line in enumerate(lines):
        stripped = line.strip()
        if f'"{op_id}"' not in stripped:
            continue

        # Parse: ("op_name", torch.op, [dtypes]) or ("op_name", lambda..., dtypes_expr)
        # Try standard pattern first: "op_name", torch.xxx, ...
        match = re.search(
            rf'\(\s*"{re.escape(op_id)}"\s*,\s*([\w.]+)\s*(?:,\s*(.+?))?\s*\)',
            stripped
        )
        if match:
            torch_op = match.group(1)
            third_arg = match.group(2).strip().rstrip(",") if match.group(2) else None
        else:
            # Fallback: match lambda/partial patterns, e.g. ("op_name", lambda a: a.op_(), DTYPES)
            match = re.search(
                rf'\(\s*"{re.escape(op_id)}"\s*,\s*(lambda[^,]*)\s*,\s*(.+?)\s*\)',
                stripped
            )
            if not match:
                continue
            torch_op = match.group(1).strip()
            third_arg = match.group(2).strip().rstrip(",")

        # Determine benchmark type from file name
        bench_type = "generic"
        if "unary_pointwise" in basename:
            bench_type = "unary"
        elif "binary_pointwise" in basename:
            bench_type = "binary"

        # Determine dtypes
        dtypes = None
        if third_arg:
            dtypes = third_arg.rstrip(",")

        return {
            "type": bench_type,
            "torch_op": torch_op,
            "dtypes": dtypes,
            "op_id": op_id,
        }

    return None


def generate_benchmark_file(blocks, op, bench_source_file, repo=None):
    """Generate independent benchmark file from extracted blocks."""
    # 冲突场景（存在裸算子）下 op_id 保留前导下划线（文件名/op_name 用）；
    # 否则去掉前导下划线。pytest marker 名不能以下划线开头，用 underscore 前缀。
    if repo:
        op_id, op_mark = resolve_op_names(repo, op)
    else:
        op_id = get_op_id(op)
        op_mark = id_to_mark(op_id)

    has_class = any(t == "class" for t, _ in blocks)
    has_test = any(t == "test" for t, _ in blocks)
    list_entry = next((b for t, b in blocks if t == "list_entry"), None)

    # Case A: standalone class + input_fn + test function → combine them
    if has_class or has_test:
        all_block_text = "\n".join(b for _, b in blocks if isinstance(b, str))
        needs_consts = ("consts." in all_block_text or "FLOAT_DTYPES" in all_block_text
                        or "INT_DTYPES" in all_block_text)
        needs_generator = "Generator" in all_block_text
        needs_flag_gems = "flag_gems." in all_block_text

        header_parts = []
        if needs_generator:
            header_parts.append("from typing import Generator")
        header_parts.append("import pytest")
        header_parts.append("import torch")
        if needs_flag_gems:
            header_parts.append("\nimport flag_gems")
        header = "\n".join(header_parts) + "\n\nfrom . import base"
        if needs_consts:
            header += ", consts"
        header += "\n"

        parts = [header]
        for btype, block in blocks:
            if not isinstance(block, str):
                continue
            if btype == "test":
                block = re.sub(rf"def test_perf_{re.escape(op_id)}\b",
                               f"def test_{op_id}", block)
                # Normalize double-underscore test names the worktree kept (e.g.
                # ``def test__cslt_compress`` → ``def test_cslt_compress``).
                if op.startswith("_"):
                    block = re.sub(rf"def test_{re.escape(op)}\b",
                                   f"def test_{op_id}", block)
            parts.append(f"\n\n{block}")

        content = "\n".join(parts)

        # Add base. prefix to benchmark classes/helpers if not already prefixed
        for cls in ["GenericBenchmark", "GenericBenchmarkExcluse1D",
                     "GenericBenchmarkExcluse3D", "GenericBenchmark2DOnly",
                     "GenericBenchmark4DOnly", "UnaryPointwiseBenchmark",
                     "BinaryPointwiseBenchmark", "UnaryReductionBenchmark",
                     "BlasBenchmark", "Benchmark"]:
            content = re.sub(rf"(?<!base\.)(?<!\w){cls}\(", f"base.{cls}(", content)
            content = re.sub(rf"(?<!base\.)(?<!\w){cls}\)", f"base.{cls})", content)
        for helper in ["generate_tensor_input", "Config"]:
            content = re.sub(rf"(?<!base\.)(?<!\w){helper}\b", f"base.{helper}", content)
        content = content.replace("base.base.", "base.")

        # Add consts. prefix
        for const in ["FLOAT_DTYPES", "INT_DTYPES", "EXTRA_INT_DTYPES", "BOOL_DTYPES",
                      "COMPLEX_DTYPES", "FLOAT16_DTYPES"]:
            content = re.sub(rf"(?<!consts\.)(?<!\w){const}\b", f"consts.{const}", content)
        content = content.replace("consts.consts.", "consts.")

        # Normalize the pytest mark and op_name to the canonical op_mark/op_id.
        # The worktree generator may keep the leading underscore (e.g.
        # ``@pytest.mark._cslt_compress`` / ``op_name="_cslt_compress``); rewrite both
        # the underscore-prefixed and the stripped-id forms to the resolved mark/id.
        if op.startswith("_"):
            content = re.sub(
                rf"@pytest\.mark\.{re.escape(op)}\b",
                f"@pytest.mark.{op_mark}", content,
            )
            content = re.sub(
                rf'op_name="{re.escape(op)}"',
                f'op_name="{op_id}"', content,
            )
        content = re.sub(
            rf'op_name="{re.escape(get_op_id(op))}"',
            f'op_name="{op_id}"', content,
        )
        # Variant-specific marks: ``test_<op_id>_out`` is a real overload and
        # must carry ``@pytest.mark.<op_mark>_out`` instead of the base mark.
        bm_lines = content.split("\n")
        for i, line in enumerate(bm_lines):
            m = re.match(rf"def (test_{re.escape(op_id)})_(\w+)\b", line)
            if not m:
                continue
            suffix = m.group(2)
            if suffix not in ("out",):
                continue
            for j in range(i - 1, max(i - 6, -1), -1):
                mk = re.match(rf"(\s*@pytest\.mark\.){re.escape(op_mark)}\b\s*$", bm_lines[j])
                if mk:
                    bm_lines[j] = f"{mk.group(1)}{op_mark}_{suffix}"
                    break
        content = "\n".join(bm_lines)
        # Drop the worktree's pytest.mark setattr boilerplate (the mark is now a
        # plain legal name, no registration shim needed) and its accompanying import.
        content = re.sub(
            r"from _pytest\.mark\.structures import Mark, MarkDecorator\n+", "", content,
        )
        content = re.sub(
            r"setattr\(\s*\n\s*pytest\.mark,\s*\n\s*\"[^\"]+\",\s*\n"
            r"\s*MarkDecorator\(Mark\([^)]*\),\s*_ispytest=True\),\s*\n\s*\)\s*\n+",
            "", content,
        )

        # Rule 2: a hardcoded ``dtypes=[torch.float32, torch.float16]`` (or other
        # multi-dtype literal) in the benchmark needs a preceding comment so the
        # dtype-hardcoding check treats the restriction as intentional. The
        # generator restricts dtypes for numerical/precision reasons; document it
        # rather than silently broadening to ``consts.FLOAT_DTYPES``.
        _dtype_literal = re.compile(
            r"(\bdtypes\s*=\s*)(\[torch\.(?:float16|float32|bfloat16|float64)"
            r"(?:,\s*torch\.(?:float16|float32|bfloat16|float64))*\])"
        )
        bm_lines = content.split("\n")
        for i, line in enumerate(bm_lines):
            if _dtype_literal.search(line) and (
                i == 0 or not bm_lines[i - 1].strip().startswith("#")
            ):
                bm_lines.insert(
                    i,
                    "        # Restricted dtype list per the worktree generator "
                    "(numerical-stability / precision scope).",
                )
                break
        content = "\n".join(bm_lines)

    # Case B: list entry → generate standard benchmark
    elif list_entry:
        info = list_entry
        torch_op = info["torch_op"]
        dtypes_str = info.get("dtypes")

        if info["type"] == "unary":
            cls = "base.UnaryPointwiseBenchmark"
        elif info["type"] == "binary":
            cls = "base.BinaryPointwiseBenchmark"
        else:
            cls = "base.GenericBenchmark"

        # Build dtypes argument
        if dtypes_str:
            dtypes_arg = f"dtypes={dtypes_str}"
            needs_consts = False
        else:
            dtypes_arg = "dtypes=consts.FLOAT_DTYPES"
            needs_consts = True

        header = "import pytest\nimport torch\n\nfrom . import base"
        if needs_consts:
            header += ", consts"
        header += "\n"

        content = f"""{header}


@pytest.mark.{op_mark}
def test_{op_id}():
    bench = {cls}(
        op_name="{op_id}",
        torch_op={torch_op},
        {dtypes_arg},
    )
    bench.run()
"""
    else:
        return None

    if not content.endswith("\n"):
        content += "\n"
    return content


def extract_benchmark(op, worktree, repo, dry_run):
    section("Step 3: Benchmark 文件")
    op_id = get_op_id(op)  # 读取 worktree 用（生成名，无冲突）
    # 最终文件名用 resolve_op_names：冲突场景保留前导下划线。
    file_op_id = resolve_op_names(repo, op)[0]
    dst = os.path.join(repo, f"benchmark/test_{file_op_id}.py")

    fpath, content = find_benchmark_code(op, worktree)
    if not fpath:
        fatal(f"worktree benchmark 中未找到 {op_id} 相关代码")

    ok(f"找到 benchmark: {os.path.basename(fpath)}")

    blocks = extract_benchmark_block(content, op, fpath)
    if not blocks:
        fatal(f"无法提取 benchmark 代码块")

    ok(f"提取到 {len(blocks)} 个代码块: {[t for t, _ in blocks]}")

    # Capture module-level helper functions (e.g. ``_prune_to_2x4``) referenced by
    # the benchmark class/get_input_iter/test function. Same transitive-closure
    # approach as the test file: worktree generators define these at module scope
    # and the benchmark references them, so they must be carried over.
    block_text = "\n".join(b for _, b in blocks if isinstance(b, str))
    helper_blocks = []
    discovered = set()
    # Functions already captured by Strategies 1/2/3 (class/input_fn/test) are
    # in ``blocks``; exclude their ``def`` signatures from the helper frontier so
    # we don't re-extract them as duplicates. The frontier regex matches
    # ``def <name>(`` signatures too, which would otherwise re-add an already-
    # captured input_fn as a helper (causing F811 redefinition).
    already_in_blocks = set()
    for _, b in blocks:
        if not isinstance(b, str):
            continue
        already_in_blocks.update(re.findall(r"^\s*def (\w+)\s*\(", b, re.MULTILINE))
    already_in_blocks.add(op_id)
    frontier = {h.rstrip("(").strip() for h in re.findall(r"\b_+\w+\s*\(", block_text)}
    frontier = {h for h in frontier if not h.startswith("test_") and h not in already_in_blocks}
    while frontier:
        hname = frontier.pop()
        if hname in discovered or hname in already_in_blocks:
            continue
        discovered.add(hname)
        m = re.search(rf"^def {re.escape(hname)}\b", content, re.MULTILINE)
        if not m:
            continue
        hblock = extract_function_block(content, hname)
        if not hblock or hblock in helper_blocks:
            continue
        helper_blocks.append(hblock)
        for sub in re.findall(r"\b(_+\w+)\s*\(", hblock):
            sub = sub.rstrip("(").strip()
            if sub.startswith("test_") or sub in discovered:
                continue
            frontier.add(sub)
    for hb in reversed(helper_blocks):
        blocks.insert(0, ("helper", hb))
    if helper_blocks:
        ok(f"提取到 {len(helper_blocks)} 个 benchmark 辅助函数")

    bench_content = generate_benchmark_file(blocks, op, fpath, repo=repo)

    if not bench_content:
        fatal("无法生成 benchmark 文件内容")

    if dry_run:
        ok(f"[DRY] 将写入 {dst}")
        print(f"    预览:\n{bench_content[:500]}")
    else:
        with open(dst, "w") as f:
            f.write(bench_content)
        ok(f"已生成: {dst}")


