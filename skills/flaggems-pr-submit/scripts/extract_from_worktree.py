# tune_configs.yaml (Nvidia backend) — copy the op's autotune config block.
# ---------------------------------------------------------------------------

def _parse_yaml_top_level_blocks(content):
    """Return list of (key, block_text, start_line, end_line) for top-level keys.

    A top-level key is a line matching ``^<key>:$`` at column 0. Its block runs
    until the next top-level key or EOF.
    """
    blocks = []
    cur_key = None
    cur_start = None
    lines = content.split("\n")
    for i, line in enumerate(lines):
        if re.match(r"^[A-Za-z_][A-Za-z0-9_]*:$", line):
            if cur_key is not None:
                blocks.append((cur_key, cur_start, i))
            cur_key = line[:-1]
            cur_start = i
    if cur_key is not None:
        blocks.append((cur_key, cur_start, len(lines)))
    return lines, blocks


def insert_tune_configs(op, worktree, repo, dry_run):
    """Copy the op's autotune config block from the worktree's Nvidia
    ``tune_configs.yaml`` into the repo's, if the worktree has one and the
    repo does not. The block is inserted in alphabetical order of the key.
    """
    section("Step 7: tune_configs.yaml (Nvidia)")
    # The kernel may use runtime.get_tuned_config("<resolved_id>") or
    # runtime.get_tuned_config("<op>"). Try both, plus variant ids registered
    # in the worktree yaml (_out variants share the kernel's config usually,
    # but the worktree may still list them).
    resolved_id = resolve_op_names(repo, op)[0]
    candidate_keys = []
    for k in [op, resolved_id, get_op_id(op)]:
        if k and k not in candidate_keys:
            candidate_keys.append(k)

    wt_yaml = os.path.join(
        worktree, "src/flag_gems/runtime/backend/_nvidia/tune_configs.yaml"
    )
    repo_yaml = os.path.join(
        repo, "src/flag_gems/runtime/backend/_nvidia/tune_configs.yaml"
    )
    if not os.path.isfile(wt_yaml):
        warn("worktree 无 tune_configs.yaml，跳过")
        return
    if not os.path.isfile(repo_yaml):
        warn("repo 无 tune_configs.yaml，跳过")
        return

    with open(wt_yaml) as f:
        wt_content = f.read()
    with open(repo_yaml) as f:
        repo_content = f.read()

    wt_lines, wt_blocks = _parse_yaml_top_level_blocks(wt_content)
    repo_lines, repo_blocks = _parse_yaml_top_level_blocks(repo_content)
    repo_keys = {k for k, _, _ in repo_blocks}

    inserted_any = False
    for key in candidate_keys:
        wt_block = next(((s, e) for k, s, e in wt_blocks if k == key), None)
        if wt_block is None:
            continue
        if key in repo_keys:
            ok(f"tune_configs.yaml 已包含 {key}")
            continue
        block_text = "\n".join(wt_lines[wt_block[0]:wt_block[1]]).rstrip() + "\n"
        # Find alphabetical insertion point among existing top-level keys.
        insert_line = len(repo_lines)
        for k, s, _ in repo_blocks:
            if key < k:
                insert_line = s
                break
        if dry_run:
            ok(f"[DRY] 将插入 tune_configs.yaml: {key} (在行 {insert_line})")
        else:
            new_lines = repo_lines[:insert_line] + block_text.split("\n") + repo_lines[insert_line:]
            with open(repo_yaml, "w") as f:
                f.write("\n".join(new_lines))
            ok(f"tune_configs.yaml 插入 {key} 在行 {insert_line}")
        inserted_any = True
        # refresh repo lines/keys for subsequent inserts
        with open(repo_yaml) as f:
            repo_content = f.read()
        repo_lines, repo_blocks = _parse_yaml_top_level_blocks(repo_content)
        repo_keys = {k for k, _, _ in repo_blocks}

    if not inserted_any:
        ok("tune_configs.yaml 无需更新（kernel 不依赖外部 autotune 配置）")


