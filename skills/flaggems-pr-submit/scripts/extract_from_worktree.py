class Colors:
    OK = "\033[92m"
    FAIL = "\033[91m"
    BOLD = "\033[1m"
    CYAN = "\033[96m"
    END = "\033[0m"


def ok(msg):
    print(f"  {Colors.OK}✓{Colors.END} {msg}")


def warn(msg):
    print(f"  {Colors.CYAN}⚠{Colors.END} {msg}")


def fatal(msg):
    print(f"  {Colors.FAIL}✗ FATAL: {msg}{Colors.END}")
    sys.exit(1)


def section(msg):
    print(f"\n{Colors.BOLD}[{msg}]{Colors.END}")


def get_op_id(op_name):
    return op_name.lstrip("_")


def _strip_leading_duplicate_copyright(rest):
    """Strip a repeated Copyright/License comment block immediately following the
    required header (the generator sometimes appends a second copy)."""
    body_lines = []
    skipping = True
    for line in rest.split("\n"):
        if skipping:
            if line.strip() == "" or line.lstrip().startswith("#"):
                continue
            skipping = False
        body_lines.append(line)
    return "\n".join(body_lines)


def normalize_kernel_header(content):
    if content.startswith(REQUIRED_KERNEL_HEADER):
        rest = content[len(REQUIRED_KERNEL_HEADER):]
        rest = _strip_leading_duplicate_copyright(rest)
        return REQUIRED_KERNEL_HEADER + rest.lstrip("\n")

    if content.startswith(COPYRIGHT_LICENSE_HEADER):
        rest = content[len(COPYRIGHT_LICENSE_HEADER):]
        if rest.startswith(KERNELGEN_HEADER):
            rest = rest[len(KERNELGEN_HEADER):]
            rest = _strip_leading_duplicate_copyright(rest)
            return REQUIRED_KERNEL_HEADER + rest.lstrip("\n")
        if rest.startswith("# Generated by KernelGen"):
            rest = rest.split("\n", 1)[1] if "\n" in rest else ""
            rest = _strip_leading_duplicate_copyright(rest)
        return REQUIRED_KERNEL_HEADER + rest.lstrip("\n")

    if content.startswith("# Generated by KernelGen"):
        content = content.split("\n", 1)[1] if "\n" in content else ""

    # Fallback: the content already begins with a Copyright/License block (the
    # worktree kernel ships its own). Strip that existing header before prefixing
    # the canonical REQUIRED_KERNEL_HEADER, otherwise the Copyright block would
    # appear twice.
    if content.startswith(COPYRIGHT_LICENSE_HEADER.rstrip("\n")):
        stripped = COPYRIGHT_LICENSE_HEADER.rstrip("\n")
        content = content[len(stripped):]
    content = _strip_leading_duplicate_copyright(content)

    return REQUIRED_KERNEL_HEADER + content.lstrip("\n")


