def insert_ops_init(op, worktree, repo, dry_run):
    section("Step 4: ops/__init__.py")
    wt_init = os.path.join(worktree, "src/flag_gems/ops/__init__.py")
    repo_init = os.path.join(repo, "src/flag_gems/ops/__init__.py")

    # Extract import line and __all__ entries from worktree
    with open(wt_init) as f:
        wt_content = f.read()

    # Try both op and op without trailing underscore (inplace ops stored in base module).
    # Order matters: prefer the exact ``op`` module match. Only fall back to the
    # stripped (base) module when the exact inplace-module import is absent —
    # otherwise a file that imports BOTH ``_add_relu`` (non-inplace) and
    # ``_add_relu_`` (inplace) would match the non-inplace line first (it appears
    # earlier) and then be wrongly rewritten to the inplace module name while
    # keeping the non-inplace imported symbol.
    module_names = [op]
    if op.endswith("_"):
        module_names.append(op.rstrip("_"))

    wt_lines = wt_content.split("\n")

    def _capture_full_import(start_idx, mod):
        """Capture a ``from ... import ...`` statement that may span multiple
        lines (``from flag_gems.ops.<mod> import (\n    name,\n)``). Walks
        forward until brackets balance. Returns the full statement text and
        the comma-separated imported-names string."""
        stmt_lines = [wt_lines[start_idx]]
        balance = (
            wt_lines[start_idx].count("(") + wt_lines[start_idx].count("[")
            - wt_lines[start_idx].count(")") - wt_lines[start_idx].count("]")
        )
        j = start_idx + 1
        while balance > 0 and j < len(wt_lines):
            stmt_lines.append(wt_lines[j])
            balance += (
                wt_lines[j].count("(") + wt_lines[j].count("[")
                - wt_lines[j].count(")") - wt_lines[j].count("]")
            )
            j += 1
        full = "\n".join(stmt_lines)
        # Extract the imported-names portion (after ``import``).
        names_str = ""
        m = re.search(r"import\s*\(?(.+?)\)?\s*$", full, re.DOTALL)
        if m:
            names_str = m.group(1)
        # Strip trailing/leading whitespace and split on commas.
        return full, names_str

    import_line = None
    used_module = None
    names = []
    # First pass: exact ``op`` module only.
    for i, line in enumerate(wt_lines):
        if re.match(rf"^from flag_gems\.ops\.{re.escape(op)} import\b", line):
            import_line, names_str = _capture_full_import(i, op)
            used_module = op
            names = [n.strip().rstrip(",") for n in names_str.split(",") if n.strip() and n.strip() != "("]
            break
    # Second pass: fallback to stripped module (inplace stored in base module).
    if import_line is None and op.endswith("_"):
        base_mod = op.rstrip("_")
        for i, line in enumerate(wt_lines):
            if re.match(rf"^from flag_gems\.ops\.{re.escape(base_mod)} import\b", line):
                import_line, names_str = _capture_full_import(i, base_mod)
                used_module = base_mod
                names = [n.strip().rstrip(",") for n in names_str.split(",") if n.strip() and n.strip() != "("]
                break

    if not import_line:
        fatal(f"worktree ops/__init__.py 中未找到 {op} 的 import")

    ok(f"import: {import_line.splitlines()[0]}{'...' if len(import_line.splitlines()) > 1 else ''}")
    ok(f"导出名: {names}")

    # Fix import line module name: worktree may use base name (logical_not) but
    # repo uses op name (logical_not_) for the kernel file.
    if used_module != op:
        import_line = import_line.replace(
            f"from flag_gems.ops.{used_module} import",
            f"from flag_gems.ops.{op} import"
        )
        ok(f"import 模块名修正: {used_module} → {op}")

    # Read repo file
    with open(repo_init) as f:
        repo_content = f.read()

    # Insert import line in alphabetical order
    repo_lines = repo_content.split("\n")
    import_section_end = 0
    existing_imports = []
    for i, line in enumerate(repo_lines):
        if line.startswith("from flag_gems.ops."):
            existing_imports.append((i, line))
            import_section_end = i

    # Check if already exists
    if any(import_line in line for _, line in existing_imports):
        ok("import 已存在，跳过")
    else:
        # Find insertion point by alphabetical order
        module_name = op
        insert_idx = import_section_end + 1
        for i, line in existing_imports:
            match = re.match(r"from flag_gems\.ops\.(\w+) import", line)
            if match:
                existing_mod = match.group(1)
                sort_key_existing = (not existing_mod.startswith("_"), existing_mod)
                sort_key_new = (not module_name.startswith("_"), module_name)
                if sort_key_new < sort_key_existing:
                    insert_idx = i
                    break
                insert_idx = i + 1

        repo_lines.insert(insert_idx, import_line)
        ok(f"import 插入位置: 行 {insert_idx + 1}")

    # Insert into __all__
    # Find __all__ block
    all_start = None
    all_end = None
    for i, line in enumerate(repo_lines):
        if "__all__" in line and "=" in line:
            all_start = i
        if all_start and line.strip() == "]":
            all_end = i
            break

    if all_start and all_end:
        # Extract current __all__ entries
        all_entries = []
        for i in range(all_start, all_end + 1):
            matches = re.findall(r'"(\w+)"', repo_lines[i])
            all_entries.extend(matches)

        for name in names:
            if name in all_entries:
                ok(f'__all__ 已包含 "{name}"')
                continue

            # Find insertion point
            insert_idx = all_end
            for i in range(all_start + 1, all_end):
                match = re.search(r'"(\w+)"', repo_lines[i])
                if match:
                    existing = match.group(1)
                    if name < existing:
                        insert_idx = i
                        break
                    insert_idx = i + 1

            entry = f'    "{name}",'
            repo_lines.insert(insert_idx, entry)
            all_end += 1
            ok(f'__all__ 插入 "{name}" 在行 {insert_idx + 1}')

    new_content = "\n".join(repo_lines)

    if dry_run:
        ok("[DRY] ops/__init__.py 将被更新")
    else:
        with open(repo_init, "w") as f:
            f.write(new_content)
        ok("ops/__init__.py 已更新")


