#!/usr/bin/env bash
set -euo pipefail

# prepare_kernel.sh <op> [--repo-dir DIR] [--funcs func1,func2]
# 从 worktree 复制 kernel + 添加 KernelGen 首行 + 注册 __init__.py
#
# --funcs: 要从 kernel 中导出的 wrapper 函数名（逗号分隔）
#          如果不指定，自动检测 kernel 中的顶层 def（排除 _ 开头的私有函数）
#
# 路径来自 --repo-dir / FLAGGEMS_REPO。详见 config.sh 顶部的环境变量说明。

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
# shellcheck source=config.sh
source "$SCRIPT_DIR/config.sh"

OP="${1:?Usage: prepare_kernel.sh <op> [--repo-dir DIR] [--funcs func1,func2]}"
shift

REPO_DIR=""
FUNCS=""
while [[ $# -gt 0 ]]; do
    case "$1" in
        --repo-dir) REPO_DIR="$2"; shift 2 ;;
        --funcs) FUNCS="$2"; shift 2 ;;
        *) echo "Unknown option: $1" >&2; exit 1 ;;
    esac
done

REPO_DIR="$(resolve_repo_dir "$REPO_DIR")"
OPS_DIR="${REPO_DIR}/${ASCEND_OPS}"
WORKTREE_KERNEL="${REPO_DIR}/.worktrees/gen-${OP}/${ASCEND_OPS}/${OP}.py"
TARGET_KERNEL="${OPS_DIR}/${OP}.py"
INIT_PY="${OPS_DIR}/__init__.py"

KERNELGEN_LINE="# Generated by KernelGen: https://github.com/flagos-ai/KernelGen"

# 1. 复制 kernel
if [[ ! -f "$WORKTREE_KERNEL" ]]; then
    echo "ERROR: Worktree kernel 不存在: $WORKTREE_KERNEL" >&2
    exit 1
fi

if [[ ! -d "$OPS_DIR" ]]; then
    echo "ERROR: Ascend ops 目录不存在: $OPS_DIR" >&2
    exit 1
fi

cp "$WORKTREE_KERNEL" "$TARGET_KERNEL"
echo "[✓] 复制 kernel: ${OP}.py"

# 2. 添加 KernelGen 首行（用 python 处理，避免 GNU/BSD sed 的 -i 差异）
if "$PYTHON_BIN" - "$TARGET_KERNEL" "$KERNELGEN_LINE" <<'PYEOF'
import sys

path, marker = sys.argv[1], sys.argv[2]
with open(path, "r", encoding="utf-8") as f:
    content = f.read()
if content.split("\n", 1)[0].strip() == marker:
    sys.exit(1)  # 已存在
with open(path, "w", encoding="utf-8") as f:
    f.write(marker + "\n" + content)
PYEOF
then
    echo "[✓] 添加 KernelGen 首行"
else
    echo "[✓] KernelGen 首行已存在"
fi

# 3. 检测要导出的函数
if [[ -z "$FUNCS" ]]; then
    FUNCS=$("$PYTHON_BIN" - "$TARGET_KERNEL" <<'PYEOF'
import ast
import sys

with open(sys.argv[1], encoding="utf-8") as f:
    tree = ast.parse(f.read())
funcs = [
    node.name
    for node in ast.iter_child_nodes(tree)
    if isinstance(node, ast.FunctionDef) and not node.name.startswith("_")
]
print(",".join(funcs))
PYEOF
)
    if [[ -z "$FUNCS" ]]; then
        echo "ERROR: 未检测到可导出的函数（非 _ 开头）" >&2
        exit 1
    fi
    echo "[✓] 自动检测导出函数: $FUNCS"
fi

# 4. 注册 __init__.py（op / funcs / path 通过 argv 传入，避免 shell 插值）
"$PYTHON_BIN" - "$OP" "$FUNCS" "$INIT_PY" <<'PYEOF'
import re
import sys

op, funcs_arg, init_path = sys.argv[1], sys.argv[2], sys.argv[3]
funcs = [f for f in funcs_arg.split(",") if f]

with open(init_path, "r", encoding="utf-8") as f:
    content = f.read()

# --- Add import line ---
import_line = f"from .{op} import {', '.join(funcs)}"

if import_line in content:
    print(f"[✓] Import 已存在: {import_line}")
else:
    # Find correct alphabetical position among "from .xxx import" lines
    lines = content.split("\n")
    insert_idx = None
    in_imports = False
    for i, line in enumerate(lines):
        m = re.match(r"^from \.(\w+) import", line)
        if m:
            in_imports = True
            mod_name = m.group(1)
            if mod_name > op and insert_idx is None:
                insert_idx = i
        elif in_imports and not line.startswith("from .") and not line.startswith("    ") and not line.startswith(")"):
            if insert_idx is None:
                insert_idx = i
            break

    if insert_idx is None:
        print("ERROR: 无法找到 import 插入位置", file=sys.stderr)
        sys.exit(1)

    lines.insert(insert_idx, import_line)
    content = "\n".join(lines)
    print(f"[✓] 添加 import: {import_line} (行 {insert_idx + 1})")

# --- Add to __all__ ---
all_additions = []
for func in funcs:
    if f'"{func}"' in content:
        print(f'[✓] __all__ 已有: "{func}"')
    else:
        all_additions.append(func)

if all_additions:
    lines = content.split("\n")
    for func in all_additions:
        entry = f'    "{func}",'
        insert_idx = None
        in_all = False
        for i, line in enumerate(lines):
            if "__all__" in line and "=" in line:
                in_all = True
                continue
            if in_all:
                stripped = line.strip().strip('"').strip("'").rstrip(",")
                if stripped == "]":
                    if insert_idx is None:
                        insert_idx = i
                    break
                if stripped > func and insert_idx is None:
                    insert_idx = i
        if insert_idx is not None:
            lines.insert(insert_idx, entry)
            print(f'[✓] 添加 __all__: "{func}" (行 {insert_idx + 1})')
        else:
            print(f"ERROR: 无法找到 __all__ 插入位置 for {func}", file=sys.stderr)
            sys.exit(1)
    content = "\n".join(lines)

with open(init_path, "w", encoding="utf-8") as f:
    f.write(content)
PYEOF

echo ""
echo "=== prepare_kernel 完成 ==="
echo "Kernel: $TARGET_KERNEL"
echo "导出函数: $FUNCS"
echo "__init__.py 已更新"
