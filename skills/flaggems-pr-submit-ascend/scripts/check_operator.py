#!/usr/bin/env python3
"""FlagGems 昇腾特化算子 PR 提交前自动化检查脚本。

用法:
    python check_operator.py <operator_name> [--repo-dir /path/to/FlagGems]

环境变量:
    FLAGGEMS_REPO             仓库路径（--repo-dir 的默认值）
    FLAGGEMS_ASCEND_OPS       Ascend kernel 目录（仓库内相对路径）
    FLAGGEMS_UPSTREAM_REMOTE  上游 remote 名，默认 upstream
    FLAGGEMS_BASE_BRANCH      上游基线分支，默认 master

检查项:
    1. kernel 文件存在且内容合规（路径: _ascend/ops/<op>.py）
    2. _ascend/ops/__init__.py 注册
    3. operators.yaml 条目（含重复检测、下划线命名）
    4. 独立测试文件（含 dtype 硬编码检测、mark 命名）
    5. 独立 benchmark 文件（含 dtype 硬编码检测、mark 命名）
    6. 代码质量（重复函数、print、unused import 等）
    7. 上游冲突检查
    8. 命名规范（下划线前缀算子的 mark/id 规则）
"""

import argparse
import ast
import os
import re
import subprocess
import sys

import yaml


ASCEND_OPS = os.environ.get("FLAGGEMS_ASCEND_OPS", "src/flag_gems/runtime/backend/_ascend/ops")
UPSTREAM_REMOTE = os.environ.get("FLAGGEMS_UPSTREAM_REMOTE", "upstream")
BASE_BRANCH = os.environ.get("FLAGGEMS_BASE_BRANCH", "master")
UPSTREAM_REF = f"{UPSTREAM_REMOTE}/{BASE_BRANCH}"


class Colors:
    OK = "\033[92m"
    WARN = "\033[93m"
    FAIL = "\033[91m"
    BOLD = "\033[1m"
    END = "\033[0m"


def ok(msg):
    print(f"  {Colors.OK}✓{Colors.END} {msg}")


def warn(msg):
    print(f"  {Colors.WARN}⚠{Colors.END} {msg}")


def fail(msg):
    print(f"  {Colors.FAIL}✗{Colors.END} {msg}")


def section(msg):
    print(f"\n{Colors.BOLD}[{msg}]{Colors.END}")


class OperatorChecker:
    def __init__(self, op_name, repo_dir):
        self.op_name = op_name
        self.repo_dir = repo_dir
        self.errors = []
        self.warnings = []

        # 下划线前缀的算子，mark 和 yaml id 需要去掉前导下划线
        self.op_id = op_name.lstrip("_")
        self.has_leading_underscore = op_name.startswith("_")

        self.kernel_path = os.path.join(repo_dir, ASCEND_OPS, f"{op_name}.py")
        self.ops_init_path = os.path.join(repo_dir, ASCEND_OPS, "__init__.py")
        self.yaml_path = os.path.join(repo_dir, "conf/operators.yaml")
        # 测试/benchmark 文件名使用 op_id（去掉前导下划线）
        self.test_path = os.path.join(repo_dir, "tests", f"test_{self.op_id}.py")
        self.bench_path = os.path.join(repo_dir, "benchmark", f"test_{self.op_id}.py")
        # 旧版错误路径（用于检测）
        if self.has_leading_underscore:
            self.wrong_test_path = os.path.join(repo_dir, "tests", f"test_{op_name}.py")
            self.wrong_bench_path = os.path.join(repo_dir, "benchmark", f"test_{op_name}.py")
        else:
            self.wrong_test_path = None
            self.wrong_bench_path = None

    def run_all(self):
        if self.has_leading_underscore:
            section("命名规则提示")
            ok(f"检测到下划线前缀算子: {self.op_name}")
            ok(f"  文件名/函数名/import: 保留 {self.op_name}")
            ok(f"  pytest mark / yaml id: 使用 {self.op_id}（去掉前导下划线）")

        self.check_kernel()
        self.check_ops_init()
        self.check_operators_yaml()
        self.check_test_file()
        self.check_benchmark_file()
        self.check_code_quality()
        self.check_upstream_conflict()
        self.print_summary()
        return len(self.errors) == 0

    def check_kernel(self):
        section("Kernel 文件检查")
        if not os.path.isfile(self.kernel_path):
            self.errors.append(f"kernel 文件不存在: {self.kernel_path}")
            fail(f"文件不存在: {self.kernel_path}")
            return

        ok(f"文件存在: {self.kernel_path}")

        with open(self.kernel_path, "r") as f:
            content = f.read()

        first_line = content.split("\n")[0].strip()
        if first_line.startswith("# Generated by KernelGen"):
            ok("首行 KernelGen 注释存在")
        else:
            self.errors.append("kernel 文件首行缺少 KernelGen 注释")
            fail("首行应为: # Generated by KernelGen: https://github.com/flagos-ai/KernelGen")

        if "import logging" not in content or "logger" not in content:
            self.warnings.append("kernel 文件未使用 logging 模块")
            warn("未使用 logging 模块（建议用 logger = logging.getLogger(__name__)）")
        else:
            ok("使用了 logging 模块")

        if "print(" in content:
            self.errors.append("kernel 文件中使用了 print()")
            fail("包含 print() 调用 — 应使用 logger.debug()")
        else:
            ok("无 print() 调用")

        self._check_duplicate_functions(content, self.kernel_path)

        try:
            tree = ast.parse(content)
        except SyntaxError as e:
            self.errors.append(f"kernel 文件语法错误: {e}")
            fail(f"Python 语法错误: {e}")
            return

        # 检查未使用的 import torch
        has_torch_import = False
        torch_used_in_annotation_or_call = False
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                for alias in node.names:
                    if alias.name == "torch":
                        has_torch_import = True
            if isinstance(node, ast.Attribute):
                if isinstance(node.value, ast.Name) and node.value.id == "torch":
                    torch_used_in_annotation_or_call = True
            if isinstance(node, ast.Name) and node.id == "torch":
                torch_used_in_annotation_or_call = True

        if has_torch_import and not torch_used_in_annotation_or_call:
            self.warnings.append("kernel 文件 import torch 但未实际使用（flake8 F401）")
            warn("import torch 但未使用 — flake8 会报 F401，提交前需删除")
        elif has_torch_import:
            ok("import torch 已使用")
        else:
            ok("无多余的 torch import")

        # 收集导出函数和 jit 函数信息
        exported = [
            n.name for n in ast.walk(tree)
            if isinstance(n, ast.FunctionDef)
            and not any(
                (isinstance(d, ast.Attribute) and d.attr == "jit")
                or (isinstance(d, ast.Name) and d.id == "jit")
                for d in n.decorator_list
            )
        ]
        jit_funcs = [
            n.name for n in ast.walk(tree)
            if isinstance(n, ast.FunctionDef) and any(
                (isinstance(d, ast.Attribute) and d.attr == "jit")
                or (isinstance(d, ast.Name) and d.id == "jit")
                for d in n.decorator_list
            )
        ]

        if exported:
            ok(f"导出函数: {', '.join(exported)}")
        else:
            self.warnings.append("未找到非 jit 导出函数")
            warn("未找到公开的非 @triton.jit 函数")

        if jit_funcs:
            ok(f"Triton kernel: {', '.join(jit_funcs)}")

        self._kernel_exported = exported
        self._kernel_jit_funcs = jit_funcs

    def check_ops_init(self):
        section("_ascend/ops/__init__.py 注册检查")
        if not os.path.isfile(self.ops_init_path):
            self.errors.append("_ascend/ops/__init__.py 不存在")
            fail("文件不存在")
            return

        with open(self.ops_init_path, "r") as f:
            content = f.read()

        import_pattern = rf"from \.{re.escape(self.op_name)} import"
        if re.search(import_pattern, content):
            ok(f"找到 import: from .{self.op_name} import ...")

            try:
                tree_init = ast.parse(content)
                imported_names = []
                for node in ast.walk(tree_init):
                    if isinstance(node, ast.ImportFrom) and node.level == 1 and node.module == self.op_name:
                        for alias in node.names:
                            imported_names.append(alias.asname or alias.name)
                if imported_names:
                    ok(f"  导入名称: {', '.join(imported_names)}")
                    if hasattr(self, "_kernel_jit_funcs"):
                        leaked = set(imported_names) & set(self._kernel_jit_funcs)
                        if leaked:
                            self.errors.append(f"_ascend/ops/__init__.py 不应导出 triton kernel 函数: {', '.join(leaked)}")
                            fail(f"  不应导出 triton kernel: {', '.join(leaked)}")
            except SyntaxError:
                pass
        else:
            self.errors.append(f"_ascend/ops/__init__.py 中缺少 from .{self.op_name} import ...")
            fail(f"缺少 import 行: from .{self.op_name} import ...")

        all_match = re.search(r"__all__\s*=\s*\[([^\]]+)\]", content, re.DOTALL)
        if all_match:
            all_content = all_match.group(1)
            if f'"{self.op_name}"' in all_content or f"'{self.op_name}'" in all_content:
                ok(f'__all__ 中包含 "{self.op_name}"')
            else:
                self.errors.append(f'__all__ 中缺少 "{self.op_name}"')
                fail(f'__all__ 中缺少 "{self.op_name}"')
        else:
            self.warnings.append("未找到 __all__ 定义")
            warn("未找到 __all__ 列表")

        self._check_alphabetical_order_init(content)

    def check_operators_yaml(self):
        section("conf/operators.yaml 检查")
        if not os.path.isfile(self.yaml_path):
            self.errors.append("operators.yaml 不存在")
            fail("文件不存在")
            return

        with open(self.yaml_path, "r") as f:
            try:
                data = yaml.safe_load(f)
            except yaml.YAMLError as e:
                self.errors.append(f"operators.yaml 解析失败: {e}")
                fail(f"YAML 解析失败: {e}")
                return

        if not isinstance(data, dict):
            self.errors.append("operators.yaml 内容为空或格式不正确（顶层应为映射）")
            fail("operators.yaml 内容为空或格式不正确")
            return

        ops = data.get("ops") or []

        # 检查重复条目
        id_counts = {}
        for op in ops:
            op_id = op.get("id", "")
            id_counts[op_id] = id_counts.get(op_id, 0) + 1

        # 查找匹配的条目（使用 op_id，即去掉前导下划线的版本）
        found = None
        for op in ops:
            if op.get("id") == self.op_id:
                found = op
                break

        if not found:
            self.errors.append(f"operators.yaml 中缺少 id: {self.op_id}")
            fail(f"缺少条目 id: {self.op_id}")
            if self.has_leading_underscore:
                # 检查是否错误地用了带下划线的 id
                for op in ops:
                    if op.get("id") == self.op_name:
                        self.errors.append(
                            f"operators.yaml 中 id 使用了 '{self.op_name}'（带下划线），"
                            f"应改为 '{self.op_id}'（去掉前导下划线）"
                        )
                        fail(f"  发现错误的 id: '{self.op_name}' → 应为 '{self.op_id}'")
                        break
            return

        ok(f"找到条目 id: {self.op_id}")

        # 检查重复
        if id_counts.get(self.op_id, 0) > 1:
            self.errors.append(
                f"operators.yaml 中 id '{self.op_id}' 出现了 {id_counts[self.op_id]} 次（应只有 1 次）"
            )
            fail(f"  id '{self.op_id}' 重复了 {id_counts[self.op_id]} 次!")
        else:
            ok("  无重复条目")

        required_fields = ["id", "description", "for", "labels", "kind", "stages"]
        for field in required_fields:
            if field in found:
                ok(f"  字段 {field}: ✓")
            else:
                self.errors.append(f"operators.yaml 条目缺少字段: {field}")
                fail(f"  缺少字段: {field}")

        # 检查 description 不是模板占位符
        desc = found.get("description", "")
        if desc and ("Computes the " + self.op_name + " operation" in desc
                     or "Computes the " + self.op_id + " operation" in desc):
            self.warnings.append("operators.yaml description 是模板占位符，应写实际描述")
            warn("  description 是模板占位符 — 应从 PyTorch 文档提取实际描述")

        labels = found.get("labels", [])
        if "KernelGen" not in labels:
            self.warnings.append("operators.yaml labels 中缺少 KernelGen")
            warn("  labels 中缺少 'KernelGen'（新增算子应包含）")
        else:
            ok("  labels 包含 'KernelGen'")

        if "aten" not in labels:
            self.warnings.append("operators.yaml labels 中缺少 aten 标签")
            warn("  labels 中缺少 'aten'")

        # 检查 for 字段是否包含正确的 aten op name（保留原始下划线）
        for_list = found.get("for", [])
        if for_list and self.op_name not in for_list:
            self.warnings.append(
                f"operators.yaml for 字段中未包含 '{self.op_name}'（aten op 原始名称应保留下划线）"
            )
            warn(f"  for 字段建议包含 '{self.op_name}'")

    def check_test_file(self):
        section("测试文件检查")
        if not os.path.isfile(self.test_path):
            # 检查是否用了错误的文件名（带下划线）
            if self.wrong_test_path and os.path.isfile(self.wrong_test_path):
                self.errors.append(
                    f"测试文件名错误: test_{self.op_name}.py → 应为 test_{self.op_id}.py（去掉前导下划线）"
                )
                fail(f"文件名错误: test_{self.op_name}.py → 应为 test_{self.op_id}.py")
            else:
                self.errors.append(f"测试文件不存在: {self.test_path}")
                fail(f"文件不存在: tests/test_{self.op_id}.py")
            return

        ok(f"文件存在: tests/test_{self.op_id}.py")

        with open(self.test_path, "r") as f:
            content = f.read()

        # pytest mark 检查（使用去掉下划线的 op_id）
        correct_mark = f"@pytest.mark.{self.op_id}"
        wrong_mark = f"@pytest.mark.{self.op_name}" if self.has_leading_underscore else None

        if correct_mark in content:
            ok(f"pytest mark 正确: {correct_mark}")
        elif wrong_mark and wrong_mark in content:
            self.errors.append(
                f"测试文件 pytest mark 使用了 '{wrong_mark}'（带下划线），应改为 '{correct_mark}'"
            )
            fail(f"pytest mark 错误: {wrong_mark} → 应为 {correct_mark}")
        else:
            self.errors.append(f"测试文件缺少 {correct_mark}")
            fail(f"缺少 pytest mark: {correct_mark}")

        if "from . import accuracy_utils as utils" in content:
            ok("使用相对导入 accuracy_utils")
        elif "from tests import accuracy_utils" in content:
            self.errors.append("测试文件使用了绝对导入而非相对导入")
            fail("应使用 'from . import accuracy_utils as utils'（相对导入）")
        else:
            self.warnings.append("测试文件中未找到 accuracy_utils 导入")
            warn("未找到 accuracy_utils 导入")

        if "flag_gems.use_gems()" in content:
            ok("使用 flag_gems.use_gems() 上下文")
        else:
            self.warnings.append("测试文件中未使用 flag_gems.use_gems()")
            warn("未找到 flag_gems.use_gems() — 确认测试方式是否正确")

        if "gems_assert_close" in content or "gems_assert_equal" in content:
            ok("使用 gems_assert_close/equal 进行比较")
        else:
            self.errors.append("测试文件未使用 gems_assert_close 或 gems_assert_equal")
            fail("未使用 utils.gems_assert_close 或 utils.gems_assert_equal")

        if "print(" in content:
            self.errors.append("测试文件中使用了 print()")
            fail("包含 print() — 禁止在 test case 中 print")

        if "utils.to_reference" in content:
            ok("使用 utils.to_reference 获取 golden reference")
        else:
            self.warnings.append("测试文件未使用 utils.to_reference")
            warn("未使用 utils.to_reference — 确认 golden reference 来源")

        # 私有 API 检查
        self._check_private_torch_api(content, "测试文件")

        # dtype 硬编码检查
        self._check_dtype_hardcoding(content, "测试文件",
                                     correct_const="utils.FLOAT_DTYPES")

    def check_benchmark_file(self):
        section("Benchmark 文件检查")
        if not os.path.isfile(self.bench_path):
            if self.wrong_bench_path and os.path.isfile(self.wrong_bench_path):
                self.errors.append(
                    f"benchmark 文件名错误: test_{self.op_name}.py → 应为 test_{self.op_id}.py（去掉前导下划线）"
                )
                fail(f"文件名错误: test_{self.op_name}.py → 应为 test_{self.op_id}.py")
            else:
                self.errors.append(f"benchmark 文件不存在: {self.bench_path}")
                fail(f"文件不存在: benchmark/test_{self.op_id}.py")
            return

        ok(f"文件存在: benchmark/test_{self.op_id}.py")

        with open(self.bench_path, "r") as f:
            content = f.read()

        # pytest mark 检查（使用去掉下划线的 op_id）
        correct_mark = f"@pytest.mark.{self.op_id}"
        wrong_mark = f"@pytest.mark.{self.op_name}" if self.has_leading_underscore else None

        if correct_mark in content:
            ok(f"pytest mark 正确: {correct_mark}")
        elif wrong_mark and wrong_mark in content:
            self.errors.append(
                f"benchmark pytest mark 使用了 '{wrong_mark}'（带下划线），应改为 '{correct_mark}'"
            )
            fail(f"pytest mark 错误: {wrong_mark} → 应为 {correct_mark}")
        else:
            self.errors.append(f"benchmark 缺少 {correct_mark}")
            fail(f"缺少 pytest mark: {correct_mark}")

        if "from . import base" in content:
            ok("使用相对导入 base 模块")
        else:
            self.warnings.append("benchmark 未使用相对导入 base")
            warn("未使用 'from . import base' — 应使用 benchmark 封装类")

        benchmark_classes = [
            "UnaryPointwiseBenchmark",
            "BinaryPointwiseBenchmark",
            "ReductionBenchmark",
            "UnaryPointwiseIsCloseBenchmark",
            "GenericBenchmark",
            "BlasBenchmark",
        ]
        found_class = False
        for cls in benchmark_classes:
            if cls in content:
                found_class = True
                ok(f"使用 benchmark 封装类: {cls}")
                break

        if not found_class:
            if "bench.run()" in content or ".run()" in content:
                ok("使用了 benchmark 运行方法")
            else:
                self.warnings.append("benchmark 未使用标准封装类")
                warn("未使用标准 benchmark 封装类 — 确认是否为自定义 benchmark")

        if "print(" in content:
            self.warnings.append("benchmark 中有 print()")
            warn("包含 print() — 建议移除")

        # op_name 检查（应使用去掉下划线的 op_id）
        if self.has_leading_underscore:
            wrong_op_name = f'op_name="{self.op_name}"'
            correct_op_name = f'op_name="{self.op_id}"'
            if wrong_op_name in content:
                self.errors.append(
                    f"benchmark op_name 使用了 '{self.op_name}'（带下划线），应为 '{self.op_id}'"
                )
                fail(f"op_name 错误: {wrong_op_name} → 应为 {correct_op_name}")
            elif correct_op_name in content:
                ok(f"op_name 正确: {correct_op_name}")

        # 私有 API 检查
        self._check_private_torch_api(content, "benchmark 文件")

        # dtype 硬编码检查
        self._check_dtype_hardcoding(content, "benchmark 文件",
                                     correct_const="consts.FLOAT_DTYPES")

    def _check_private_torch_api(self, content, file_label):
        """检查测试/benchmark 中是否直接调用了 torch._ 私有 API。
        私有 API 在不同 PyTorch 版本中可能不存在，应使用公开 API。
        """
        private_calls = re.findall(r"torch\.(_[a-z]\w*)\(", content)
        # 过滤掉 torch._C 等模块级调用和常见合法用法
        skip = {"_C", "_jit_internal", "_utils", "_dynamo"}
        private_calls = [c for c in private_calls if c not in skip]
        if private_calls:
            unique = sorted(set(private_calls))
            self.errors.append(
                f"{file_label}中直接调用了 torch 私有 API: {', '.join('torch.' + c for c in unique)}"
                f"。私有 API 在不同 PyTorch 版本中可能不存在，应使用对应的公开 API"
            )
            fail(
                f"调用了私有 API: {', '.join('torch.' + c for c in unique)}"
                f" → 应替换为公开 API"
            )
        else:
            ok(f"未调用 torch 私有 API")

    def _check_dtype_hardcoding(self, content, file_label, correct_const):
        """检查 dtype 是否使用了硬编码列表而非统一常量。
        如果硬编码行的上一行有注释说明原因（如 CUDA 不支持某精度），降级为 ok。
        """
        hardcoded_patterns = [
            r"\[torch\.float32\]",
            r"\[torch\.float64\]",
            r"\[torch\.float16\]",
            r"\[torch\.bfloat16\]",
            r"\[torch\.float16,\s*torch\.float32\]",
            r"\[torch\.float32,\s*torch\.float64\]",
        ]
        lines = content.split("\n")
        for pattern in hardcoded_patterns:
            match = re.search(pattern, content)
            if match:
                match_pos = match.start()
                line_no = content[:match_pos].count("\n")
                has_comment = False
                if line_no > 0:
                    prev_line = lines[line_no - 1].strip()
                    if prev_line.startswith("#") and (
                        "not implemented" in prev_line.lower()
                        or "not support" in prev_line.lower()
                        or "only support" in prev_line.lower()
                        or "raise" in prev_line.lower()
                        or "runtimeerror" in prev_line.lower()
                    ):
                        has_comment = True

                if has_comment:
                    ok(f"dtype 硬编码 {match.group()}（有注释说明原因，允许）")
                    return

                self.errors.append(
                    f"{file_label}中 dtype 使用了硬编码 {match.group()}，应使用 {correct_const}"
                    f"（如因 CUDA 限制无法使用全部精度，需在上一行加注释说明原因）"
                )
                fail(f"dtype 硬编码: {match.group()} → 应使用 {correct_const}（或加注释说明原因）")
                return

        if correct_const.split(".")[-1] in content or "FLOAT_DTYPES" in content or "INT_DTYPES" in content:
            ok("dtype 使用统一常量")
        else:
            self.warnings.append(f"{file_label}中未检测到标准 dtype 常量")
            warn(f"未检测到 {correct_const} — 确认 dtype 来源")

    def check_code_quality(self):
        section("代码质量检查")

        for filepath in [self.kernel_path, self.test_path, self.bench_path]:
            if not os.path.isfile(filepath):
                continue
            with open(filepath, "r") as f:
                content = f.read()
            if not content.endswith("\n"):
                relpath = os.path.relpath(filepath, self.repo_dir)
                self.warnings.append(f"{relpath} 文件末尾缺少换行")
                warn(f"{relpath} 文件末尾缺少换行 — end-of-file-fixer 会报错")

        for filepath in [self.kernel_path, self.test_path, self.bench_path]:
            if not os.path.isfile(filepath):
                continue
            with open(filepath, "r") as f:
                lines = f.readlines()
            for i, line in enumerate(lines, 1):
                if line.rstrip() != line.rstrip("\n").rstrip():
                    relpath = os.path.relpath(filepath, self.repo_dir)
                    self.warnings.append(f"{relpath}:{i} 行尾有空白字符")
                    warn(f"{relpath}:{i} 行尾空白 — trailing-whitespace hook 会报错")
                    break

        for filepath in [self.kernel_path, self.test_path, self.bench_path]:
            if not os.path.isfile(filepath):
                continue
            with open(filepath, "r") as f:
                lines = f.readlines()
            for i, line in enumerate(lines, 1):
                if len(line.rstrip("\n")) > 120:
                    relpath = os.path.relpath(filepath, self.repo_dir)
                    self.warnings.append(f"{relpath}:{i} 行长度超过 120 字符")
                    warn(f"{relpath}:{i} 行长度 {len(line.rstrip())} > 120 — flake8 会报错")
                    break

    def check_upstream_conflict(self):
        section("上游冲突检查")
        try:
            ref_check = subprocess.run(
                ["git", "rev-parse", "--verify", "--quiet", UPSTREAM_REF],
                capture_output=True,
                text=True,
                cwd=self.repo_dir,
            )
            if ref_check.returncode != 0:
                self.warnings.append(f"无法解析 {UPSTREAM_REF}，跳过上游冲突检查")
                warn(f"无法解析 {UPSTREAM_REF} — 先 git fetch {UPSTREAM_REMOTE}")
                return

            result = subprocess.run(
                ["git", "show", f"{UPSTREAM_REF}:{ASCEND_OPS}/{self.op_name}.py"],
                capture_output=True,
                text=True,
                cwd=self.repo_dir,
            )
            if result.returncode == 0:
                self.errors.append(f"算子 {self.op_name} 已存在于上游 {UPSTREAM_REF}")
                fail("算子已存在于上游! 不应提交此 PR")
                return
        except FileNotFoundError:
            self.warnings.append("未找到 git 命令，跳过上游冲突检查")
            warn("未找到 git 命令 — 跳过上游冲突检查")
            return

        ok(f"算子 {self.op_name} 未在上游发现冲突")

    def _check_duplicate_functions(self, content, filepath):
        try:
            tree = ast.parse(content)
        except SyntaxError:
            return

        func_names = []
        for node in ast.walk(tree):
            if isinstance(node, ast.FunctionDef):
                func_names.append(node.name)

        seen = set()
        duplicates = set()
        for name in func_names:
            if name in seen:
                duplicates.add(name)
            seen.add(name)

        if duplicates:
            relpath = os.path.relpath(filepath, self.repo_dir)
            self.errors.append(f"{relpath} 中有重复函数定义: {', '.join(duplicates)}")
            fail(f"重复函数定义: {', '.join(duplicates)}")
        else:
            ok("无重复函数定义")

    def _check_alphabetical_order_init(self, content):
        import_lines = re.findall(r"^from \.(\w+) import", content, re.MULTILINE)
        if import_lines:
            sorted_lines = sorted(import_lines, key=lambda x: (not x.startswith("_"), x))
            if import_lines == sorted_lines:
                ok("import 行按字母序排列")
            else:
                for i, (actual, expected) in enumerate(zip(import_lines, sorted_lines)):
                    if actual != expected:
                        self.warnings.append(f"ops/__init__.py import 顺序可能不对（{actual} vs {expected}）")
                        warn(f"import 顺序可能不对 — isort 可自动修复")
                        break

    def print_summary(self):
        section("检查汇总")
        print(f"\n  算子: {self.op_name}")
        if self.has_leading_underscore:
            print(f"  算子 ID（mark/yaml）: {self.op_id}")
        print(f"  错误: {Colors.FAIL}{len(self.errors)}{Colors.END}")
        print(f"  警告: {Colors.WARN}{len(self.warnings)}{Colors.END}")

        if self.errors:
            print(f"\n  {Colors.FAIL}{Colors.BOLD}必须修复:{Colors.END}")
            for e in self.errors:
                print(f"    - {e}")

        if self.warnings:
            print(f"\n  {Colors.WARN}{Colors.BOLD}建议修复:{Colors.END}")
            for w in self.warnings:
                print(f"    - {w}")

        if not self.errors:
            print(f"\n  {Colors.OK}{Colors.BOLD}所有必要检查通过 ✓{Colors.END}")
        else:
            print(f"\n  {Colors.FAIL}{Colors.BOLD}存在 {len(self.errors)} 个必须修复的问题 ✗{Colors.END}")

    def get_changed_files(self):
        files = [
            f"{ASCEND_OPS}/{self.op_name}.py",
            f"{ASCEND_OPS}/__init__.py",
            f"tests/test_{self.op_id}.py",
            f"benchmark/test_{self.op_id}.py",
            "conf/operators.yaml",
        ]
        return [f for f in files if os.path.isfile(os.path.join(self.repo_dir, f))]


def main():
    parser = argparse.ArgumentParser(description="FlagGems 昇腾特化算子 PR 提交前检查")
    parser.add_argument("operator", help="算子名称（如 special_erfcx, _cholesky_solve_helper）")
    parser.add_argument(
        "--repo-dir",
        default=os.environ.get("FLAGGEMS_REPO", ""),
        help="FlagGems 仓库路径（默认取 $FLAGGEMS_REPO）",
    )
    parser.add_argument("--list-files", action="store_true", help="仅输出涉及的文件列表")
    args = parser.parse_args()

    if not args.repo_dir:
        print(
            "ERROR: 未指定 FlagGems 仓库路径。\n"
            "  方式 1: --repo-dir /path/to/FlagGems\n"
            "  方式 2: export FLAGGEMS_REPO=/path/to/FlagGems",
            file=sys.stderr,
        )
        sys.exit(2)
    if not os.path.isdir(args.repo_dir):
        print(f"ERROR: 仓库路径不存在: {args.repo_dir}", file=sys.stderr)
        sys.exit(2)

    checker = OperatorChecker(args.operator, args.repo_dir)

    if args.list_files:
        for f in checker.get_changed_files():
            print(f)
        return

    print(f"{Colors.BOLD}FlagGems 昇腾特化算子 PR 检查: {args.operator}{Colors.END}")
    print(f"仓库路径: {args.repo_dir}")

    success = checker.run_all()
    sys.exit(0 if success else 1)


if __name__ == "__main__":
    main()
